from typing import Dict, List, Union

import torch
from torch import Tensor, nn
from transformers import AutoModel, AutoTokenizer, CLIPModel


class TextEncoder(nn.Module):
    """Encode text into projected pooled and token-level representations."""

    def __init__(
        self,
        model_name: str,
        hidden_dim: int,
        encoder_type: str = "clip",
        freeze: bool = True,
        max_length: int = 32,
        output_type: str = "pooled",
        freeze_projection: bool = False,
    ):
        super().__init__()
        self.freeze = freeze
        self.max_length = max_length
        self.output_type = output_type.lower()
        if self.output_type not in {"pooled", "token"}:
            raise ValueError("text_encoder_output must be 'pooled' or 'token'")
        self.tokenizer = AutoTokenizer.from_pretrained(model_name)
        if encoder_type.lower() == "clip":
            # The original V6.1 checkpoint stores the inner CLIP text
            # transformer directly under ``text_encoder.backbone``.
            self.backbone = CLIPModel.from_pretrained(model_name).text_model
            # Some Transformers releases persist this deterministic buffer
            # while others do not. It is regenerated by the model and is not
            # a learned checkpoint parameter.
            self.backbone.embeddings._non_persistent_buffers_set.add("position_ids")
        elif encoder_type.lower() in {"bert", "auto"}:
            self.backbone = AutoModel.from_pretrained(model_name)
        else:
            raise ValueError(f"Unsupported text encoder type: {encoder_type}")

        text_dim = int(self.backbone.config.hidden_size)
        self.projection = nn.Linear(text_dim, hidden_dim)
        if freeze:
            self.backbone.requires_grad_(False)
        if freeze_projection:
            self.projection.requires_grad_(False)

    @property
    def vocab_size(self) -> int:
        return int(self.backbone.config.vocab_size)

    def tokenize(self, texts: Union[List[str], str], device: torch.device) -> Dict[str, Tensor]:
        return self.tokenizer(
            texts,
            padding="max_length",
            truncation=True,
            max_length=self.max_length,
            return_tensors="pt",
        ).to(device)

    def forward(
        self,
        texts: Union[List[str], str],
        device: torch.device,
    ) -> Dict[str, Tensor]:
        tokens = self.tokenize(texts, device)
        if self.freeze:
            self.backbone.eval()
            with torch.no_grad():
                outputs = self.backbone(**tokens)
        else:
            outputs = self.backbone(**tokens)

        pooled = getattr(outputs, "pooler_output", None)
        if pooled is None:
            pooled = outputs.last_hidden_state[:, 0]
        return {
            "pooled": self.projection(pooled),
            "tokens": self.projection(outputs.last_hidden_state),
            "attention_mask": tokens["attention_mask"],
            "input_ids": tokens["input_ids"],
        }
